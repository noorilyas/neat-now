import 'package:flutter/material.dart';

class ConfettiParticleModel {
  final double angle;
  final double velocity;
  final double size;
  final Color color;
  final double delay;
  final double rotationSpeed;
  final int shape;

  const ConfettiParticleModel({
    required this.angle,
    required this.velocity,
    required this. size,
    required this.color,
    required this.delay,
    required this.rotationSpeed,
    required this.shape,
  });
}